import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** The manifest selects direct runtime dependencies; the frozen install supplies exact versions and original license text. */
export function generateNotice(root) {
  const manifest = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  const sections = Object.entries(manifest.dependencies).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([alias, requested]) => {
    const dir = path.join(root, "node_modules", alias);
    const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
    if (typeof pkg.license !== "string" || !pkg.license.trim()) throw new Error(`Missing license metadata: ${alias}`);
    const label = `${alias === pkg.name ? "" : `${alias} → `}${pkg.name}@${pkg.version} — ${pkg.license}`;
    const files = readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && /^(licen[sc]e|copying|notice)([.-].*)?$/i.test(entry.name))
      .map((entry) => entry.name).sort();
    const texts = files.map((name) => `${name}:\n${readFileSync(path.join(dir, name), "utf8").replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").trim()}`).join("\n\n");
    return `${label}\nDeclared dependency: ${requested}\n\n${texts || "The published package includes no license/notice file; the license identifier above is from its package metadata."}`;
  });
  return `Orbit web — third-party notices\n\nGenerated by pnpm licenses:write from package.json direct runtime dependencies.\nVersions and original license/notice texts come from the frozen pnpm install.\nRun pnpm licenses:check after dependency changes.\n\n${sections.join("\n\n" + "=".repeat(72) + "\n\n")}\n`;
}

export function checkNotice(root) {
  const expected = generateNotice(root);
  let actual;
  try { actual = readFileSync(path.join(root, "NOTICE"), "utf8"); } catch { /* Missing is also stale. */ }
  if (actual !== expected) throw new Error("NOTICE is missing or stale; run pnpm licenses:write and review the changes");
}

